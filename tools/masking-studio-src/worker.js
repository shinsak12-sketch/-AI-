const WORKER_BODY = [
'var WBS={};',
'function csvFromAoa(aoa){',
'  var out=new Array(aoa.length);',
'  for(var r=0;r<aoa.length;r++){',
'    var row=aoa[r], m=row.length, cells=new Array(m);',
'    for(var c=0;c<m;c++){',
'      var v=row[c];',
'      if(v==null||v===""){ cells[c]=""; continue; }',
'      var s=typeof v==="string"?v:String(v);',
'      cells[c]=(s.indexOf(",")>=0||s.indexOf("\\"")>=0||s.indexOf("\\n")>=0||s.indexOf("\\r")>=0)',
'        ? "\\""+s.replace(/"/g,"\\"\\"")+"\\"" : s;',
'    }',
'    out[r]=cells.join(",");',
'  }',
'  return out.join("\\n");',
'}',
'onmessage=function(e){',
'  var d=e.data, id=d.id;',
'  try{',
'    if(d.cmd==="load"){',
'      WBS[d.key] = d.text!=null ? XLSX.read(d.text,{type:"string",raw:true,dense:true})',
'                                : XLSX.read(new Uint8Array(d.buf),{type:"array",cellDates:true,dense:true});',
'      postMessage({id:id,ok:true});',
'    } else if(d.cmd==="build"){',
'      if(d.isCsv){',
'        postMessage({id:id,text:csvFromAoa(d.aoa)});',
'      } else {',
'        var W=WBS[d.key];',
'        var wb=XLSX.utils.book_new(), names=(W&&W.SheetNames.indexOf(d.name)>=0)?W.SheetNames:[d.name];',
'        for(var i=0;i<names.length;i++){',
'          var n=names[i];',
'          XLSX.utils.book_append_sheet(wb, n===d.name?XLSX.utils.aoa_to_sheet(d.aoa):W.Sheets[n], n);',
'        }',
'        var out=XLSX.write(wb,{bookType:"xlsx",type:"array"});',
'        postMessage({id:id,buf:out},[out]);',
'      }',
'    } else if(d.cmd==="table"){',
'      if(d.asCsv){',
'        postMessage({id:id,text:csvFromAoa(d.map)});',
'      } else {',
'        var w2=XLSX.utils.book_new();',
'        var wsM=XLSX.utils.aoa_to_sheet(d.map); wsM["!cols"]=d.mcols;',
'        var wsI=XLSX.utils.aoa_to_sheet(d.info); wsI["!cols"]=d.icols;',
'        XLSX.utils.book_append_sheet(w2,wsM,"MAPPING");',
'        XLSX.utils.book_append_sheet(w2,wsI,"INFO");',
'        var o2=XLSX.write(w2,{bookType:"xlsx",type:"array"});',
'        postMessage({id:id,buf:o2},[o2]);',
'      }',
'    }',
'  }catch(err){ postMessage({id:id,err:String((err&&err.message)||err)}); }',
'};'].join('\n');
